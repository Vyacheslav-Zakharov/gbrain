function proposalSelectionCluster(slug: string): string {
  const separator = slug.indexOf('/');
  return separator === -1 ? slug : slug.slice(0, separator);
}

function hasSameExactContent(left: Page, right: Page): boolean {
  if ((left.source_id ?? '') !== (right.source_id ?? '')) return false;
  return Boolean(left.content_hash && left.content_hash === right.content_hash);
}

function pageIsWithinSourceScope(
  page: Page,
  scope: Pick<PageFilters, 'sourceId' | 'sourceIds'>,
): boolean {
  const allowed = scope.sourceIds?.length
    ? scope.sourceIds
    : scope.sourceId
      ? [scope.sourceId]
      : [];
  if (allowed.length === 0) return true;
  return typeof page.source_id === 'string'
    && page.source_id.length > 0
    && allowed.includes(page.source_id);
}

function sourceScopeLabel(scope: Pick<PageFilters, 'sourceId' | 'sourceIds'>): string {
  return scope.sourceIds?.length ? scope.sourceIds.join(',') : (scope.sourceId ?? '<unscoped>');
}

/**
 * Counts why candidates were retained or suppressed before scan/provider work.
 * Selected slugs remain available through durable scan rows; diagnostics keep
 * only bounded aggregate metadata.
 */
export interface ProposeTakeSelectionDiagnostics {
  candidates_considered: number;
  excluded_generated_type: number;
  excluded_index: number;
  exact_content_duplicates_suppressed: number;
  eligible_pages: number;
  selected_pages: number;
  selected_clusters: number;
}

export function selectProposeTakePagesWithDiagnostics(
  pages: Page[],
  limit: number,
): { pages: Page[]; diagnostics: ProposeTakeSelectionDiagnostics } {
  const diagnostics: ProposeTakeSelectionDiagnostics = {
    candidates_considered: pages.length,
    excluded_generated_type: 0,
    excluded_index: 0,
    exact_content_duplicates_suppressed: 0,
    eligible_pages: 0,
    selected_pages: 0,
    selected_clusters: 0,
  };
  if (!Number.isInteger(limit) || limit <= 0) return { pages: [], diagnostics };

  const clusters = new Map<string, Page[]>();
  const accepted: Page[] = [];
  for (const page of pages) {
    if (PROPOSE_TAKES_GENERATED_PAGE_TYPES.has(page.type)) {
      diagnostics.excluded_generated_type += 1;
      continue;
    }
    if (page.slug === 'index' || page.slug.endsWith('/index')) {
      diagnostics.excluded_index += 1;
      continue;
    }
    if (accepted.some(existing => hasSameExactContent(existing, page))) {
      diagnostics.exact_content_duplicates_suppressed += 1;
      continue;
    }
    accepted.push(page);
    const key = proposalSelectionCluster(page.slug);
    const rows = clusters.get(key);
    if (rows) rows.push(page);
    else clusters.set(key, [page]);
  }
  diagnostics.eligible_pages = accepted.length;

  const selected: Page[] = [];
  let offset = 0;
  while (selected.length < limit) {
    let added = false;
    for (const rows of clusters.values()) {
      const page = rows[offset];
      if (!page) continue;
      selected.push(page);
      added = true;
      if (selected.length === limit) break;
    }
    if (!added) break;
    offset += 1;
  }
  diagnostics.selected_pages = selected.length;
  diagnostics.selected_clusters = new Set(
    selected.map(page => proposalSelectionCluster(page.slug)),
  ).size;
  return { pages: selected, diagnostics };
}

/**
 * Select provider candidates deterministically from a cluster-recency input.
 * Operational status and navigation index pages are not claim evidence.
 * Round-robin across top-level path clusters prevents one recently-touched
 * project from consuming the whole source budget while preserving recency
 * within every cluster. A one-cluster source remains unconstrained.
 */
export function selectProposeTakePages(pages: Page[], limit: number): Page[] {
  return selectProposeTakePagesWithDiagnostics(pages, limit).pages;
}

export function parseProposeTakesBudget(raw: string | null, fallback = 5.0): number | null {
  if (raw === null) return fallback;
  const value = raw.trim();
  if (!/^(?:0|[1-9]\d*)(?:\.\d+)?$/.test(value)) return null;
  const parsed = Number(value);
  return Number.isFinite(parsed) && parsed >= 0 ? parsed : null;
}

function proposeMaxCallCostUsd(pricing: ModelPricing, prompt: string): number {
  const inputTokenCeiling = Buffer.byteLength(prompt, 'utf8') + PROPOSE_CHAT_FRAMING_TOKEN_CEILING;
  return (
    (inputTokenCeiling / 1_000_000) * pricing.input
    + (PROPOSE_MAX_OUTPUT_TOKENS / 1_000_000) * pricing.output
  );
}

function reconcileReportedUsage(
  requestedModel: string,
  pricing: ModelPricing,
  result: ExtractorResult,
  reservationUsd: number,
): { actualUsd: number; releasedUsd: number } | null {
  if (result.actual_model !== requestedModel || !result.usage) return null;
  const { input_tokens: input, output_tokens: output, cache_read_tokens: cacheRead, cache_creation_tokens: cacheCreation } = result.usage;
  // Canonical pricing currently has no provider-specific cache read/write rates.
  // Retain the full reservation rather than under-price cached tokens.
  if (cacheRead !== 0 || cacheCreation !== 0) return null;
  if (![input, output].every(v => Number.isFinite(v) && v >= 0)) return null;
  const actualUsd = (input / 1_000_000) * pricing.input + (output / 1_000_000) * pricing.output;
  if (!Number.isFinite(actualUsd) || actualUsd < 0 || actualUsd > reservationUsd) return null;
  return { actualUsd, releasedUsd: reservationUsd - actualUsd };
}

